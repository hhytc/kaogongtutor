import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const packs = [
  ['errrc_guokao_spatial', 'public/data/errrc/guokao_spatial_2022_2026.json'],
  ['spatial_training', 'public/data/spatial/training.json'],
];
const manifest = [];
for (const [packId, file] of packs) {
  const target = path.join(root, file);
  if (!fs.existsSync(target)) continue;
  for (const q of JSON.parse(fs.readFileSync(target, 'utf8'))) {
    manifest.push({id: q.id, version: q.version || 1, packId, track: q.track,
      category: q.category, subType: q.subType, title: q.title, source: q.source,
      ...(q.difficulty ? {difficulty: q.difficulty} : {}),
      ...(q.meta?.year ? {year: q.meta.year} : {}),
      ...(q.meta?.region ? {region: q.meta.region} : {}),
      isRealExam: Boolean(q.meta?.isRealExam), hasSimulator: Boolean(q.simulatorConfig)});
  }
}
fs.writeFileSync(path.join(root, 'src/data/spatialQuestionManifest.ts'),
  `import type { QuestionManifestItem } from './questionManifest';\n\n// Generated by scripts/build-spatial-manifest.mjs; full packs remain lazy-loaded.\nexport const SPATIAL_SUPPLEMENT_MANIFEST: QuestionManifestItem[] = ${JSON.stringify(manifest, null, 2)};\n`);
const auditPath = path.join(root, 'public/data/errrc/manifest.json');
const audit = JSON.parse(fs.readFileSync(auditPath, 'utf8'));
// Keep the original 40 metadata records and all stable IDs exactly as they were.
const originals = audit.questions.filter(q => !packs.some(([packId]) => packId === q.packId));
audit.questions = [...originals, ...manifest];
audit.total = audit.questions.length;
audit.packs = Object.fromEntries([...new Set(audit.questions.map(q => q.packId))]
  .map(id => [id, audit.questions.filter(q => q.packId === id).length]));
audit.supplementUpdatedAt = '2026-10-14';
fs.writeFileSync(auditPath, JSON.stringify(audit, null, 2) + '\n');
console.log(`Generated ${manifest.length} supplement entries; ${audit.total} external/training questions total.`);
